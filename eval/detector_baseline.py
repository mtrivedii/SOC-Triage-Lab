"""Detector-only baseline: run the deterministic detectors over every case in
cases/*.yaml and compare to ground truth. No LLM involved. This is the baseline
the AI layer must be judged against (plan Sprint 2 / Sprint 4).

For each case we parse only the log files the case lists, filter events to the
case window, drop the analyst/management IP (192.168.214.1), and run the detector
that matches each log. Writes results/detector_baseline.md and prints a summary.

Run: uv run python eval/detector_baseline.py
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

import yaml

from triage.detectors import port_scan, ssh_bruteforce, web_scan
from triage.parsers import auth_log, nginx, ufw

ROOT = Path(__file__).resolve().parent.parent
MGMT_IP = "192.168.214.1"

# log filename -> (parser module, detector module)
DISPATCH = {
    "auth.log": (auth_log, ssh_bruteforce),
    "ufw.log": (ufw, port_scan),
    "nginx_access.log": (nginx, web_scan),
}


def _ts_of(event) -> datetime | None:
    return getattr(event, "ts", None)


def _in_window(event, start: datetime, end: datetime) -> bool:
    ts = _ts_of(event)
    return ts is not None and start <= ts <= end


def run_case(case: dict) -> dict:
    start = datetime.fromisoformat(case["window"]["start"])
    end = datetime.fromisoformat(case["window"]["end"])
    alerts = []
    for rel in case["log_files"]:
        name = Path(rel).name
        if name not in DISPATCH:
            continue
        parser, detector = DISPATCH[name]
        events = [e for e in parser.parse_file(ROOT / rel) if _in_window(e, start, end)]
        alerts.extend(
            detector.detect(events, case_id=case["case_id"], exclude_ips={MGMT_IP})
        )

    detected_types = sorted({a.rule_id for a in alerts})
    attack_types = sorted(
        {m[1].ATTACK_TYPE for name, m in DISPATCH.items()
         for a in alerts if a.rule_id == m[1].RULE_ID}
    )
    expected = case["expected"]
    fired = bool(alerts)
    is_malicious = expected["verdict"] == "malicious"
    verdict_ok = fired == is_malicious
    type_ok = (not is_malicious) or (expected["attack_type"] in attack_types)
    return {
        "case_id": case["case_id"],
        "expected_verdict": expected["verdict"],
        "expected_type": expected["attack_type"],
        "fired": fired,
        "detected_rules": detected_types,
        "detected_types": attack_types,
        "verdict_ok": verdict_ok,
        "type_ok": type_ok,
        "alerts": alerts,
    }


def _counts_summary(alerts) -> str:
    return "; ".join(f"{a.rule_id} {a.counts}" for a in alerts) or "-"


def main() -> None:
    cases = [yaml.safe_load(p.read_text()) for p in sorted((ROOT / "cases").glob("*.yaml"))]
    rows = [run_case(c) for c in cases]

    mal = [r for r in rows if r["expected_verdict"] == "malicious"]
    ben = [r for r in rows if r["expected_verdict"] == "benign"]
    mal_detected = sum(1 for r in mal if r["fired"])
    mal_type_ok = sum(1 for r in mal if r["type_ok"])
    ben_false = sum(1 for r in ben if r["fired"])

    lines = [
        "# Detector-only baseline",
        "",
        (
            f"Generated by `eval/detector_baseline.py` on {datetime.now().date().isoformat()}. "
            "Deterministic detectors only, no LLM. Events filtered to each case window; "
            f"analyst IP {MGMT_IP} excluded."
        ),
        "",
        "| case | expected | expected type | detector fired | detected type | verdict ok | counts |",
        "|------|----------|---------------|----------------|---------------|------------|--------|",
    ]
    for r in rows:
        lines.append(
            f"| {r['case_id']} | {r['expected_verdict']} | {r['expected_type']} | "
            f"{'yes' if r['fired'] else 'no'} | {','.join(r['detected_types']) or '-'} | "
            f"{'OK' if r['verdict_ok'] else 'WRONG'} | {_counts_summary(r['alerts'])} |"
        )
    lines += [
        "",
        (
            f"**Malicious cases detected:** {mal_detected}/{len(mal)} "
            f"(attack-type correct: {mal_type_ok}/{len(mal)})."
        ),
        f"**Benign cases false-alarmed:** {ben_false}/{len(ben)}.",
        "",
        (
            "Counts are the detector's own evidence (failed/accepted logins, distinct ports, "
            "404s/paths). This table is the non-AI baseline the LLM layer is measured against."
        ),
    ]
    out = ROOT / "results" / "detector_baseline.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("\n".join(lines))
    print(f"\nWrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
