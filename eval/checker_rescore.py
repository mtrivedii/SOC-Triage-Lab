"""Re-score the SAVED frozen-hash runs with guardrail checker v1 and v2 (OFFLINE).

Reads results/runs.jsonl, reconstructs each case's alert deterministically, and re-runs
guardrails.check(..., version=1) and version=2 on every valid run. Writes a per-flag-type,
per-model, v1-vs-v2 count table to results/checker_v1_vs_v2.md. No API calls; the saved model
outputs are reused, so this does not depend on v1 scores and does not touch them.

Run: uv run python eval/checker_rescore.py
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import yaml

from triage.guardrails import check, load_allowlist
from triage.llm.prompts import load_prompt, prompt_hash
from triage.llm.schema import TriageResult
from triage.pipeline import alerts_for_case

ROOT = Path(__file__).resolve().parent.parent
FLAGS = (
    "hallucinated_techniques",
    "unverifiable_evidence",
    "ungrounded_ips",
    "ungrounded_numbers",
    "evidence_only_numbers",
)


def main() -> None:
    frozen = prompt_hash(load_prompt("v1"))
    allow = load_allowlist()
    alerts = {}
    for p in sorted((ROOT / "cases").glob("*.yaml")):
        c = yaml.safe_load(p.read_text())
        found = alerts_for_case(c, ROOT)
        if found:
            alerts[c["case_id"]] = found[0]

    runs = [
        json.loads(x)
        for x in (ROOT / "results" / "runs.jsonl").read_text(encoding="utf-8").splitlines()
        if x.strip()
    ]
    runs = [r for r in runs if r.get("prompt_hash") == frozen and r.get("valid")]

    # counts[(provider, version, flag)] = number of runs where that flag fired
    counts: dict[tuple, int] = defaultdict(int)
    totals: dict[str, int] = defaultdict(int)
    for r in runs:
        provider = r["provider"]
        totals[provider] += 1
        alert = alerts[r["case_id"]]
        result = TriageResult.model_validate(r["result"])
        for version in (1, 2):
            rep = check(result, alert, allow, version=version)
            for flag in FLAGS:
                if getattr(rep, flag):
                    counts[(provider, version, flag)] += 1

    providers = sorted(totals)
    intro = (
        f"Generated by `eval/checker_rescore.py`. Re-ran guardrails over {len(runs)} saved valid runs "
        f"at the frozen prompt hash `{frozen[:12]}...` (same model outputs, two checker versions)."
    )
    lines = [
        "# Guardrail checker v1 vs v2 (re-scored on saved frozen-prompt runs)",
        "",
        intro,
        "Counts are the number of runs in which each flag fired.",
        "",
        "| flag | " + " | ".join(f"{p} v1 | {p} v2" for p in providers) + " |",
        "|------|" + "|".join(["------|------"] * len(providers)) + "|",
    ]
    for flag in FLAGS:
        cells = []
        for p in providers:
            cells.append(str(counts[(p, 1, flag)]))
            cells.append(str(counts[(p, 2, flag)]))
        lines.append(f"| {flag} | " + " | ".join(cells) + " |")
    v2_note = (
        "v2 reclassifies IP octets, timestamp pieces and version fragments as parts of whole tokens "
        "(never flagged), treats window durations (first_seen-last_seen +/-1s) as grounded, and moves "
        "numbers that appear only in the untrusted evidence from `ungrounded_numbers` to the softer "
        "`evidence_only_numbers`. `unverifiable_evidence` (stitched quotes) is unchanged."
    )
    lines += [
        "",
        "Runs scored: " + ", ".join(f"{p} {totals[p]}" for p in providers) + ".",
        "",
        v2_note,
    ]
    out = ROOT / "results" / "checker_v1_vs_v2.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
